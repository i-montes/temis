"""Hand-written schema templates for the decision families an autonomous agent needs (memory,
tools, security), plus notes and ground-ops checks. Each family has several paraphrases in
Spanish and English and random option subsets, so the model learns the family, not one wording.
States are generated by the LLM; labels come from the teacher.

These are our own wordings. Clio's testing/decisiones benchmark is never used for training.
"""

from __future__ import annotations

import random

STATE_HINTS: dict[str, str] = {}


def _pick(rng: random.Random, xs):
    return rng.choice(xs)


def memory_op(rng, es):
    k = rng.randint(1, 3)
    keys = [f"m{rng.randint(10, 999)}" for _ in range(k)]
    if es:
        crit = {"nueva": "Es información nueva: ninguna memoria cercana dice lo mismo.",
                "repetida": "Ya está dicha por una memoria cercana; guardarla sería duplicar.",
                "sospechosa": "No es un hecho útil sobre la persona o su trabajo: da órdenes, intenta manipular o es ruido."}
        for m in keys:
            crit[f"corrige_{m}"] = f"Corrige o actualiza la memoria {m}: mismo tema, dato distinto o más reciente."
        instr = _pick(rng, ["¿Qué hacer con el recuerdo propuesto, comparado con las memorias cercanas?",
                            "Decide cómo tratar el texto que se quiere guardar frente a lo que ya está en memoria.",
                            "Elige la operación de memoria adecuada para la propuesta."])
        hint = f"JSON con 'propuesta' (un hecho que un agente quiere recordar) y 'memorias_cercanas' con las claves {keys} (textos ya guardados, algunos relacionados). Español."
    else:
        crit = {"new": "New information: no nearby memory says it.",
                "duplicate": "A nearby memory already says this; saving it would duplicate it.",
                "suspicious": "Not a useful fact about the person or their work: it gives orders, tries to manipulate, or is noise."}
        for m in keys:
            crit[f"updates_{m}"] = f"Corrects or updates memory {m}: same topic, different or newer detail."
        instr = _pick(rng, ["What should happen to the proposed memory given the nearby memories?",
                            "Choose the right memory operation for the proposal."])
        hint = f"JSON with 'proposal' (a fact an agent wants to remember) and 'nearby_memories' with keys {keys}. English."
    items = list(crit.items())
    rng.shuffle(items)
    return {"op": {"type": "choice", "instructions": instr, "criteria": dict(items)}}, hint


def _field(rng, es):
    """Some callers send JSON and name the field in the question (`mensaje`); others send plain text."""
    if rng.random() < 0.5:
        return None
    return _pick(rng, ["mensaje", "mensaje_de_la_persona", "peticion", "texto_usuario"] if es
                 else ["message", "user_message", "request"])


def needs_memory(rng, es):
    f = _field(rng, es)
    if f:
        if es:
            q = _pick(rng, [f"Contestar `{f}` como corresponde exige información guardada sobre quien escribe o de una charla previa.",
                            f"`{f}` depende de algo dicho antes o de datos personales guardados."])
            hint = f"JSON con la clave '{f}' (lo que la persona le escribe a su asistente) y a veces 'hora' o 'canal'. Mezcla peticiones autocontenidas con otras que dependen de algo previo. Español."
        else:
            q = f"Answering `{f}` well requires knowing something about this person that is not in the message itself."
            hint = f"JSON with key '{f}' and sometimes 'time'; mix self-contained and context-dependent requests. English."
        return {"needs_memory": {"type": "noul", "instructions": q}}, hint
    if es:
        q = _pick(rng, ["Para contestar bien el mensaje hace falta recordar algo personal de quien escribe o de una conversación anterior.",
                        "El mensaje solo se puede responder bien usando información guardada sobre la persona.",
                        "Responder este mensaje requiere memoria de largo plazo (preferencias, datos personales o charlas pasadas)."])
        hint = "Texto: un mensaje de una persona a su asistente personal. Mezcla mensajes autocontenidos con otros que dependen de cosas dichas antes ('lo de siempre', 'mi hermana', 'como te dije'). Español."
    else:
        q = _pick(rng, ["Answering this message well requires remembering something personal about the sender or an earlier conversation.",
                        "The message can only be answered well with stored information about the person."])
        hint = "Text: a message from a person to their personal assistant; mix self-contained requests with ones that depend on earlier context. English."
    return {"needs_memory": {"type": "noul", "instructions": q}}, hint


def asks_to_forget(rng, es):
    f = _field(rng, es)
    if f and es:
        q = _pick(rng, [f"Lo que escribe en `{f}` es una solicitud de eliminar el recuerdo de `memoria` (ese y no otro).",
                        f"Según `{f}`, quien escribe quiere que `memoria` deje de estar guardada."])
        hint = f"JSON con 'memoria' (un recuerdo guardado) y '{f}'. A veces pide borrar esa memoria, a veces otra, a veces solo la menciona o la corrige. Español."
        return {"forget": {"type": "noul", "instructions": q}}, hint
    if es:
        q = _pick(rng, ["La persona pide explícitamente olvidar o borrar justamente la memoria indicada.",
                        "El mensaje es una petición de eliminar esa memoria concreta (no otra, ni otra cosa)."])
        hint = "JSON con 'memoria' (un recuerdo guardado) y 'mensaje' (lo que escribe la persona). A veces pide borrar esa memoria, a veces otra, a veces solo la menciona o pide cambiarla. Español."
    else:
        q = "The person explicitly asks to forget or delete exactly this memory."
        hint = "JSON with 'memory' and 'message'; sometimes it asks to delete that memory, sometimes another one, sometimes just mentions it. English."
    return {"forget": {"type": "noul", "instructions": q}}, hint


def tools(rng, es):
    if es:
        pool = {"leer_archivos": "Atender la petición exige leer archivos del equipo.",
                "modificar_archivos": "Atender la petición exige crear, editar o borrar archivos.",
                "terminal": "Atender la petición exige ejecutar comandos en una terminal.",
                "memoria": "Atender la petición exige consultar lo que se sabe de la persona o de charlas previas.",
                "internet": "Atender la petición exige buscar o leer algo en internet.",
                "preguntar": "Antes de hacer nada hay que pedir una aclaración a la persona."}
        hint = "Texto: una petición a un agente de código y asistente personal (programación, archivos, recordatorios, preguntas generales). Español."
    else:
        pool = {"read_files": "Handling the request requires reading files on the machine.",
                "write_files": "Handling the request requires creating, editing or deleting files.",
                "shell": "Handling the request requires running terminal commands.",
                "memory": "Handling the request requires looking up what is known about the person or past chats.",
                "web": "Handling the request requires searching or reading the web.",
                "clarify": "The agent must ask the person a clarifying question first."}
        hint = "Text: a request to a coding agent / personal assistant. English."
    keys = rng.sample(list(pool), rng.randint(3, 5))
    f = _field(rng, es)
    if f:
        word = "la petición" if es else "the request"
        pool = {k: v.replace(f"Atender {word}" if es else f"Handling {word}", (f"Atender `{f}`" if es else f"Handling `{f}`"))
                for k, v in pool.items()}
        hint = (f"JSON con la clave '{f}' (petición a un agente de código y asistente personal). Español." if es
                else f"JSON with key '{f}' (a request to a coding agent / assistant). English.")
    return {k: {"type": "noul", "instructions": pool[k]} for k in keys}, hint


