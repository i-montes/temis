FAMILIES = [memory_op, needs_memory, asks_to_forget, tools, tool_choice, injection, command_safety,
            worth_remembering, memory_relation, note_link, note_tags, go_no_go]


def sample(rng: random.Random) -> dict:
    from decisor.data.families import FAMILY_WEIGHT

    fam = rng.choices(FAMILIES, weights=[FAMILY_WEIGHT.get(f.__name__, 1.0) for f in FAMILIES])[0]
    es = rng.random() < 0.65
    questions, hint = fam(rng, es)
    return {"workflow": fam.__name__, "description": hint, "domain": f"agent:{fam.__name__}",
            "language": "es" if es else "en", "questions": questions, "state_hint": hint}
